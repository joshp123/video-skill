#!/usr/bin/env python3
"""Write waveform and spectral views of every dialogue join.

Written by AI on 2026-10-22 by GPT-6 Astra, from the mixer's joins.py.
Usage: joins.py EDIT DIALOGUE [--cutlist PATH] [--output DIRECTORY] [--join N]
Each PNG stacks outgoing source, incoming source and built dialogue, with one
second either side of the edge. Source labels use the front camera's clock;
dialogue labels use film time. Red marks the outgoing edge, cyan the incoming.
"""

import argparse
import json
import subprocess
from pathlib import Path


def build(edit_folder, dialogue, cutlist, output, only_join=None):
    edit_folder = edit_folder.resolve()
    cut = json.loads((edit_folder / cutlist).read_text())
    dialogue = (edit_folder / dialogue).resolve()
    output = (edit_folder / output).resolve() if output else dialogue.parent / "joins"
    output.mkdir(parents=True, exist_ok=False)
    lav = (edit_folder / cut["media"]["lav"]["file"]).resolve()
    offset = cut["media"]["lav"]["offset_s"]
    report = []
    for number, (outgoing, incoming) in enumerate(zip(cut["audio_clips"], cut["audio_clips"][1:]), 1):
        if only_join is not None and number != only_join:
            continue
        out_time = outgoing["audio_timeline_in_s"] + outgoing["audio_out_s"] - outgoing["audio_in_s"]
        in_time = incoming["audio_timeline_in_s"]
        strips = [
            (lav, outgoing["audio_out_s"] - offset, outgoing["audio_out_s"], "outgoing source", "red"),
            (lav, incoming["audio_in_s"] - offset, incoming["audio_in_s"], "incoming source", "cyan"),
            (dialogue, out_time, out_time, "built dialogue", "red"),
        ]
        arguments, filters = [], []
        for index, (path, file_time, label_time, label, colour) in enumerate(strips):
            start = max(0, file_time - 1)
            label_start = label_time - (file_time - start)
            arguments += ["-ss", f"{start:.6f}", "-t", "2", "-i", str(path)]
            marker = round((file_time - start) * 800)
            clock = "film" if index == 2 else "front"
            title = f"{label} - {label_start:.3f} to {label_start + 2:.3f} s ({clock})"
            filters += [
                f"[{index}:a]apad=whole_dur=2,atrim=duration=2,asplit=2[w{index}][s{index}]",
                f"[w{index}]showwavespic=s=1600x120:scale=log:filter=peak:colors=lime[wave{index}]",
                f"[s{index}]showspectrumpic=s=1600x240:legend=0:stop=10000:drange=90:limit=-20[spec{index}]",
                f"[spec{index}][wave{index}]vstack=inputs=2,format=rgb24,"
                f"drawbox=x={marker}:y=0:w=2:h=ih:color={colour}:t=fill,"
                f"drawtext=fontfile=/System/Library/Fonts/Menlo.ttc:text='{title}':x=8:y=8:fontsize=22:fontcolor=white:box=1:boxcolor=black[strip{index}]",
            ]
        incoming_marker = round((in_time - max(0, out_time - 1)) * 800)
        filters += [f"[strip2]drawbox=x={incoming_marker}:y=0:w=2:h=ih:color=cyan:t=fill[built]",
                    "[strip0][strip1][built]vstack=inputs=3[out]"]
        image = output / f"join-{number:02d}.png"
        subprocess.run(["ffmpeg", "-v", "error", "-n", *arguments, "-filter_complex", ";".join(filters),
                        "-map", "[out]", "-frames:v", "1", "-update", "1", str(image)], check=True)
        report.append({"join": number, "out_line": outgoing["line"], "in_line": incoming["line"],
                       "out_front_s": outgoing["audio_out_s"], "in_front_s": incoming["audio_in_s"],
                       "out_film_s": out_time, "in_film_s": in_time, "image": image.name})
        print(f"Join {number}: {outgoing['line']} -> {incoming['line']} at {out_time:.3f} s: {image}")
    (output / "joins.json").write_text(json.dumps({
        "_about": "Generated by joins.py; written by AI on 2026-10-22 by GPT-6 Astra.",
        "dialogue": str(dialogue), "joins": report,
    }, indent=2) + "\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("edit_folder", type=Path)
    parser.add_argument("dialogue", type=Path)
    parser.add_argument("--cutlist", type=Path, default=Path("build/cutlist.json"))
    parser.add_argument("--output", type=Path)
    parser.add_argument("--join", type=int)
    args = parser.parse_args()
    build(args.edit_folder, args.dialogue, args.cutlist, args.output, args.join)
